"""Writes (or, with --check, verifies) the capacity engine's descriptor from capacity/planner.yaml, the engine's one configuration file:
every planner input becomes a request parameter (its name in kebab case), so the descriptor and the planner cannot drift.

    python3 tools/capacity_descriptor.py            write java/engine-capacity/src/main/resources/META-INF/drishti-engine/capacity.engine.yaml
    python3 tools/capacity_descriptor.py --check    exit 1 when the committed file differs
"""
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
MODULE = ROOT / "java" / "engine-capacity" / "src" / "main" / "resources"
PLANNER = MODULE / "capacity" / "planner.yaml"
DESCRIPTOR = MODULE / "META-INF" / "drishti-engine" / "capacity.engine.yaml"


def kebab(name: str) -> str:
    """TradesPerFungible -> trades-per-fungible (the same rule as Planner.paramName in Java)."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "-", name).lower()


def q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def scalar(v) -> str:
    return q(v) if isinstance(v, str) else str(v)


def build() -> str:
    plan = yaml.safe_load(PLANNER.read_text(encoding="utf-8"))
    out = [
        "# Copyright (c) 2026 Ashutosh Sinha <ajsinha@gmail.com>. All rights reserved. Drishti Engines. Proprietary: see LICENSE.",
        "# Generated by tools/capacity_descriptor.py from capacity/planner.yaml: edit the planner or the script, not this file.",
        "engine: 1",
        "id: capacity",
        "version: 0.1.0",
        "title: Capacity planner",
        "about: >-",
        "  Sizes one Drishti server from the counts an administrator types: heap, memory, disk, CPU, the settings and JVM arguments to use and the",
        "  warnings to read. It has no inputs: one evaluator runs the expressions of capacity/planner.yaml over the request's parameters, and the",
        "  explanation and the workbook are generated from the same steps.",
        "publisher: { id: com.ash.engines, name: Drishti Engines }",
        "product: drishti-platform",
        'api: "0.1"',
        "platform: { tools: \"1.1\" }",
        "inputs: {}",
        "options:",
        "  exact-path: { type: bool, default: false, forces: exact-path, label: Exact path, help: This engine has one path (no grouped scans); the option changes nothing. }",
        "params:",
    ]
    names = []
    for i in plan["inputs"]:
        p = kebab(i["name"])
        names.append(p)
        kind = i["kind"]
        t = {"int": "int", "dec": "number", "text": "text"}[kind]
        parts = [f"type: {t}", f"default: {scalar(i['default'])}", f"label: {q(i['label'])}", f"unit: {q(i['unit'])}", f"help: {q(i['hint'])}"]
        if kind != "text":
            parts.insert(2, "min: 0")
        if "choices" in i:
            parts.insert(2, "allowed: [" + ", ".join(scalar(c) for c in i["choices"]) + "]")
        out.append(f"  {p}: {{ {', '.join(parts)} }}")
    out += [
        "outputs:",
        "  figures:",
        "    title: Figures",
        "    about: Every computed number of the plan, in the planner's order (results, calibration, numeric settings and JVM arguments).",
        "    params: [" + ", ".join(names) + "]",
        "    key: [NAME]",
        "    order: [ORDINAL]",
        "    columns:",
        "      - { name: ORDINAL, type: integer, nullable: false, label: Order }",
        "      - { name: SECTION, type: string, nullable: false, label: Section }",
        "      - { name: NAME, type: string, nullable: false, label: Name }",
        "      - { name: VALUE, type: number, nullable: false, label: Value, measure: true, exact: \"relative:1e-9\" }",
        "  lines:",
        "    title: Text lines",
        "    about: Every computed text of the plan: the settings, the JVM arguments, the command line, the YAML block and the warnings.",
        "    params: [" + ", ".join(names) + "]",
        "    key: [NAME]",
        "    order: [ORDINAL]",
        "    columns:",
        "      - { name: ORDINAL, type: integer, nullable: false, label: Order }",
        "      - { name: SECTION, type: string, nullable: false, label: Section }",
        "      - { name: NAME, type: string, nullable: false, label: Name }",
        "      - { name: TEXT, type: string, nullable: false, label: Text }",
        "  catalogue:",
        "    title: Catalogue",
        "    about: Every figure and line with its label, unit, why and expression, as the planner file states them (no parameters).",
        "    key: [NAME]",
        "    order: [ORDINAL]",
        "    columns:",
        "      - { name: ORDINAL, type: integer, nullable: false, label: Order }",
        "      - { name: SECTION, type: string, nullable: false, label: Section }",
        "      - { name: NAME, type: string, nullable: false, label: Name }",
        "      - { name: LABEL, type: string, nullable: false, label: Label }",
        "      - { name: UNIT, type: string, nullable: false, label: Unit }",
        "      - { name: WHY, type: string, nullable: false, label: Why }",
        "      - { name: EXPRESSION, type: string, nullable: false, label: Expression }",
        "capabilities: [ explain, workbook ]",
        "limits:",
        "  memory: { fixed-bytes: 4194304 }",
        "  cancel-latency: 200ms",
        "ui: { group: Administration, words: [ CAPACITY ] }",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not DESCRIPTOR.exists() or DESCRIPTOR.read_text(encoding="utf-8") != text:
            print(f"{DESCRIPTOR} differs from planner.yaml: run python3 tools/capacity_descriptor.py")
            return 1
        return 0
    DESCRIPTOR.write_text(text, encoding="utf-8")
    print(f"wrote {DESCRIPTOR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
